def doc(fname, title, subtitle, flow):
    path = os.path.join(OUT, fname)
    d = SimpleDocTemplate(path, pagesize=A4, leftMargin=2.2*cm, rightMargin=2.2*cm,
                          topMargin=2*cm, bottomMargin=2*cm, title=title)
    d.build([Paragraph(title, S_TITLE), Paragraph(subtitle, S_SUB)] + flow)
    print("OK", fname)

def h(t): return Paragraph(t, S_H)
def p(t): return Paragraph(t, S_P)
def ul(items):
    return ListFlowable([ListItem(Paragraph(i, S_LI), leftIndent=18) for i in items],
                        bulletType="bullet", start="•", bulletFontSize=9)

